#!/usr/bin/env node

/**
 * This script analyzes user data to generate consistent filter options.
 * It reads the mock data and optionally calls the API to find all unique
 * values for department, location, role, status, etc.
 */

const fs = require('fs');
const path = require('path');

// Path to our mock data
const mockDataPath = path.join(__dirname, '..', 'app', 'mock', 'data.ts');

// Fetch the mock data content
const mockDataContent = fs.readFileSync(mockDataPath, 'utf8');

// Extract the users array using regex (simple approach)
const usersMatch = mockDataContent.match(/export const mockUsers: User\[\] = \[([\s\S]*?)\];/);

if (!usersMatch) {
  console.error('Could not find mockUsers in the data file');
  process.exit(1);
}

// Evaluate the users array (this is a hack, in a real environment consider a safer approach)
const usersPart = usersMatch[1];
// Convert TS array to valid JSON array content
const usersJsonString = `[${usersPart}]`
  .replace(/(\w+):/g, '"$1":') // Convert property names to strings
  .replace(/'/g, '"') // Replace single quotes with double quotes
  .replace(/,(\s*[}\]])/g, '$1'); // Remove trailing commas

// Parse the modified string
let users;
try {
  users = JSON.parse(usersJsonString);
} catch (error) {
  console.error('Error parsing user data:', error);
  process.exit(1);
}

// Extract unique values
const extractUniqueValues = (data, field) => {
  const allValues = data
    .map(item => item[field])
    .filter(Boolean) // Remove null/undefined
    .map(String); // Convert to string

  // Get unique values and sort them
  return [...new Set(allValues)].sort();
};

// Generate filter options
const generateOptions = (values) => {
  return values.map(value => ({
    value,
    label: formatLabel(value)
  }));
};

// Format label for display (replace codes with friendly names)
const formatLabel = (value) => {
  // Handle specific location codes
  if (value === 'NY') return 'New York';
  if (value === 'LA') return 'Los Angeles';
  
  // Default: capitalize each word
  return value
    .split(' ')
    .map(word => word.charAt(0).toUpperCase() + word.slice(1))
    .join(' ');
};

// Extract unique values and generate filter options
const departments = extractUniqueValues(users, 'department');
const locations = extractUniqueValues(users, 'location');
const roles = extractUniqueValues(users, 'role');
const statuses = extractUniqueValues(users, 'status');

// Create filter options
const filterOptions = {
  departments: [{ value: '', label: 'All Departments' }, ...generateOptions(departments)],
  locations: [{ value: '', label: 'All Locations' }, ...generateOptions(locations)],
  roles: [{ value: '', label: 'All Roles' }, ...generateOptions(roles)],
  statuses: [{ value: '', label: 'All Status' }, ...generateOptions(statuses)]
};

// Output the results
console.log('Filter Options:');
console.log(JSON.stringify(filterOptions, null, 2));

// Create output directory if it doesn't exist
const outputDir = path.join(__dirname, '..', 'app', 'lib');
if (!fs.existsSync(outputDir)) {
  fs.mkdirSync(outputDir, { recursive: true });
}

// Generate the filter options file
const outputPath = path.join(outputDir, 'filter-options.ts');
const tsContent = `
/**
 * This file is auto-generated by scripts/analyze-user-data.js
 * Do not edit directly - regenerate if data source changes
 */

export interface FilterOption {
  value: string;
  label: string;
}

export const filterOptions = ${JSON.stringify(filterOptions, null, 2)};
`;

fs.writeFileSync(outputPath, tsContent);
console.log(`Filter options written to ${outputPath}`);